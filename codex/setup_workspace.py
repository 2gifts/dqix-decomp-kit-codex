#!/usr/bin/env python3
"""Write this checkout's machine-local Codex project config (.codex/config.toml, untracked).

    <venv>\\Scripts\\python.exe codex/setup_workspace.py [--workers 6]

Run it with the Python environment that has the kit's dependencies (capstone, pyelftools, frida,
ninja). Every Codex command, subagent and `codex exec` worker opened in this checkout then gets:
- that environment first on PATH
- DQIX_KIT, DQIX_REPO and DQIX_STATE
- git trust for the workspace, which the Windows sandbox user does not own
- write access to the whole workspace (state, decomp checkout, integration tree)
- network access for git fetch and gh
- a subagent concurrency cap

Rerun it after moving the workspace or the environment.
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
KIT = os.path.dirname(HERE)
sys.path.insert(0, KIT)
os.environ.setdefault("DQIX_NO_FRESHNESS", "1")
import kitpaths  # noqa: E402


def q(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--workers", type=int, default=6)
    a = ap.parse_args()
    for mod in ("capstone", "elftools", "ninja"):
        __import__(mod)
    scripts = os.path.dirname(sys.executable)
    # The venv's python.exe is a redirector that the sandbox user cannot resolve ("Failed to find
    # real location"), so run the base interpreter directly with the venv's packages on PYTHONPATH.
    base = os.path.dirname(getattr(sys, "_base_executable", sys.executable))
    site = os.path.join(sys.prefix, "Lib", "site-packages")
    workspace = os.path.dirname(KIT)
    git = r"C:\Program Files\Git"
    path = os.pathsep.join([base, scripts, os.path.join(git, "usr", "bin"), os.path.join(git, "bin"),
                            os.environ.get("PATH", "")])
    seen, parts = set(), []
    for p in path.split(os.pathsep):
        k = p.lower().rstrip("\\/")
        if p and k not in seen and "/" not in p:
            seen.add(k)
            parts.append(p)
    env = {
        "PATH": os.pathsep.join(parts),
        "DQIX_KIT": KIT,
        "DQIX_REPO": kitpaths.REPO.replace("/", "\\"),
        "DQIX_STATE": kitpaths.SP.replace("/", "\\"),
        "PYTHONPATH": site,
        "PYTHONUTF8": "1",
        "GIT_CONFIG_COUNT": "2",
        "GIT_CONFIG_KEY_0": "safe.directory",
        "GIT_CONFIG_VALUE_0": "*",
        "GIT_CONFIG_KEY_1": "http.sslBackend",
        "GIT_CONFIG_VALUE_1": "openssl",
    }
    lines = [
        "# Generated by codex/setup_workspace.py for this machine. Untracked; rerun it to regenerate.",
        'sandbox_mode = "workspace-write"',
        "",
        "[sandbox_workspace_write]",
        "network_access = true",
        f"writable_roots = [{q(workspace)}]",
        "",
        "[agents]",
        f"max_concurrent_threads_per_session = {a.workers}",
        "",
        "[shell_environment_policy]",
        'inherit = "all"',
        "",
        "[shell_environment_policy.set]",
    ] + [f"{k} = {q(v)}" for k, v in env.items()]
    os.makedirs(os.path.join(KIT, ".codex"), exist_ok=True)
    out = os.path.join(KIT, ".codex", "config.toml")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {out}")
    print(f"python  {sys.executable}")
    print(f"kit     {KIT}\nrepo    {kitpaths.REPO}\nstate   {kitpaths.SP}\nwrite   {workspace}")


main()
